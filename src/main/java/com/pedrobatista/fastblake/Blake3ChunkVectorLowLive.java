    private static IntVector loadWord(MemorySegment input, long block, int word) {
        long p = block + (word & ~3) * 4L;
        IntVector r0 = IntVector.fromMemorySegment(S, input, p, ByteOrder.LITTLE_ENDIAN);
        IntVector r1 = IntVector.fromMemorySegment(S, input, p + 1024, ByteOrder.LITTLE_ENDIAN);
        IntVector r2 = IntVector.fromMemorySegment(S, input, p + 2048, ByteOrder.LITTLE_ENDIAN);
        IntVector r3 = IntVector.fromMemorySegment(S, input, p + 3072, ByteOrder.LITTLE_ENDIAN);
        boolean highPair = (word & 2) != 0;
        VectorShuffle<Integer> pair = highPair ? PAIR_HI : PAIR_LO;
        IntVector t0 = r0.rearrange(pair, r1);
        IntVector t1 = r2.rearrange(pair, r3);
        return t0.rearrange((word & 1) == 0 ? COL_LO : COL_HI, t1);
    }

    private static IntVector xor(IntVector a, IntVector b) {
        return a.lanewise(VectorOperators.XOR, b);
    }

    private static IntVector ror(IntVector value, int bits) {
        return value.lanewise(VectorOperators.ROR, bits);
    }
