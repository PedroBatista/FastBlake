// Appended to the unchanged official source to access its private tree primitives.
fn fixture_input(length: usize) -> Vec<u8> {
    (0..length).map(|i| (i * 131 + (i >> 8) * 17 + 29) as u8).collect()
}
fn fixture_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}
fn fixture_cv_bytes(cv: [u32; 8]) -> Vec<u8> {
    cv.iter().flat_map(|word| word.to_le_bytes()).collect()
}
fn fixture_subtree(input: &[u8], first: u64) -> [u32; 8] {
    if input.len() <= CHUNK_LEN {
        let mut chunk = ChunkState::new(IV, first, 0);
        chunk.update(input);
        return chunk.output().chaining_value();
    }
    let leaves = (input.len() + CHUNK_LEN - 1) / CHUNK_LEN;
    let left_leaves = 1usize << ((leaves - 1).ilog2());
    let split = left_leaves * CHUNK_LEN;
    parent_cv(fixture_subtree(&input[..split], first),
              fixture_subtree(&input[split..], first + left_leaves as u64), IV, 0)
}
fn main() {
    println!("# Official BLAKE3 1.8.2 reference_impl.rs; generated by tools/tree-reference/generate.py");
    for length in [1, 63, 64, 65, 1023, 1024, 1025, 2048, 3073, 65535, 65536, 65537, 131073] {
        let input = fixture_input(length);
        for first in [0, 1, 63, 64, 127, 128, (1u64 << 32) - 2, (1u64 << 32) + 17,
                      i64::MAX as u64 - ((length - 1) / CHUNK_LEN) as u64] {
            println!("subtree\t{length}\t{first}\t{}", fixture_hex(&fixture_cv_bytes(fixture_subtree(&input, first))));
        }
    }
    for seed in [0, 1, 255] {
        let left: Vec<u8> = (0..32).map(|i| (i * 7 + seed) as u8).collect();
        let right: Vec<u8> = (0..32).map(|i| (i * 13 + seed + 37) as u8).collect();
        let mut l = [0; 8]; let mut r = [0; 8];
        words_from_little_endian_bytes(&left, &mut l);
        words_from_little_endian_bytes(&right, &mut r);
        let mut root = [0; 32];
        parent_output(l, r, IV, 0).root_output_bytes(&mut root);
        println!("parent\t{}\t{}\t{}\t{}", fixture_hex(&left), fixture_hex(&right),
                 fixture_hex(&fixture_cv_bytes(parent_cv(l, r, IV, 0))), fixture_hex(&root));
        parent_output(l, l, IV, 0).root_output_bytes(&mut root);
        println!("parent\t{}\t{}\t{}\t{}", fixture_hex(&left), fixture_hex(&left),
                 fixture_hex(&fixture_cv_bytes(parent_cv(l, l, IV, 0))), fixture_hex(&root));
    }
    for length in [65537, 131072, 131073, 8 * 1024 * 1024 + 31] {
        let mut hasher = Hasher::new();
        hasher.update(&fixture_input(length));
        let mut root = [0; 32]; hasher.finalize(&mut root);
        println!("hash\t{length}\t{}", fixture_hex(&root));
    }
}
